import { defineConfig } from 'vite';
import type { Plugin } from 'vite';
import react from '@vitejs/plugin-react';

// The cloud preview hostname changes whenever the workspace is restored, so it is
// supplied per process through PREVIEW_HOSTS (comma separated) instead of being
// baked into this file.
const previewHosts = (process.env.PREVIEW_HOSTS ?? '')
  .split(',')
  .map((host) => host.trim())
  .filter(Boolean);

/** Local API server (server/index.mjs) that talks to the crowd-data provider. */
const API_TARGET = process.env.API_TARGET ?? 'http://127.0.0.1:8787';

/**
 * Emits sw.js after the bundle is written, precaching exactly the files that
 * build produced. A hand-written service worker would not know the hashed
 * asset names, and a Workbox dependency is overkill for one page.
 */
function serviceWorker(): Plugin {
  const buildId = Date.now().toString(36);
  return {
    name: 'crowd-control-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const precache = [
        '/',
        '/manifest.webmanifest',
        ...Object.keys(bundle)
          .filter((file) => /\.(?:js|css|png|svg|webmanifest)$/.test(file))
          .map((file) => `/${file}`),
      ].filter((file, index, all) => all.indexOf(file) === index);

      const source = `/* generated by vite.config.ts */
const CACHE = 'crowd-control-${buildId}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => {}))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Crowd data: always prefer fresh numbers, but keep the last answer for offline.
  if (url.pathname.startsWith('/api/')) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request)),
    );
    return;
  }

  // Navigation: fresh shell when online, cached shell when not.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/').then((hit) => hit || caches.match('/index.html'))));
    return;
  }

  event.respondWith(
    caches.match(request).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  plugins: [react(), serviceWorker()],
  server: {
    host: '0.0.0.0',
    port: 3000,
    strictPort: true,
    allowedHosts: previewHosts.length ? previewHosts : undefined,
    proxy: {
      '/api': {
        target: API_TARGET,
        changeOrigin: true,
      },
    },
  },
});
